/* Writes a C file that holds the bytes of the domain file.
   Usage: tcc -run gen/embed.c domain/domain.lang build/domain.c
   With -r, writes build/runtime.c (S5 Q8 (a)): the bytes of each
   preprocessed runtime unit IN as one text of runtime_units.
   Usage: tcc -run gen/embed.c -r build/runtime.c IN...
   SHARED by the tcc kits. */
#include <stdio.h>
#include <string.h>

/* Writes the bytes of IN, then a 0 byte. Returns the count of bytes. */
static size_t bytes(FILE *in, FILE *out) {
  size_t count = 0;
  int c = fgetc(in);
  while (c != EOF) {
    fprintf(out, "%s0x%02x,", count % 12 == 0 ? "\n  " : " ", (unsigned)c);
    count++;
    c = fgetc(in);
  }
  fputs("\n  0x00\n};\n", out);
  return count;
}

static int embed(const char *name, FILE *in, FILE *out) {
  fprintf(out, "/* Generated by gen/embed.c from %s. Do not edit. */\n", name);
  fputs("#include <stddef.h>\n\nconst unsigned char domain_source[] = {", out);
  size_t count = bytes(in, out);
  fprintf(out, "const size_t domain_source_len = %lu;\n", (unsigned long)count);
  return ferror(in) == 0 && ferror(out) == 0;
}

static int embed_units(int count, char **names, FILE *out) {
  int ok = 1;
  fputs("/* Generated by gen/embed.c from the tcc -E text of each runtime unit. Do not edit. */\n"
        "#include <stddef.h>\n", out);
  for (int i = 0; i < count && ok; i++) {
    FILE *in = fopen(names[i], "rb");
    ok = in != NULL;
    if (ok) {
      fprintf(out, "\n/* %s */\nstatic const char runtime_unit_%d[] = {", names[i], i);
      bytes(in, out);
      ok = ferror(in) == 0;
      fclose(in);
    }
    if (!ok) fprintf(stderr, "embed: cannot read %s\n", names[i]);
  }
  fputs("\nconst char *const runtime_units[] = {", out);
  for (int i = 0; i < count; i++)
    fprintf(out, "\n  runtime_unit_%d,", i);
  fprintf(out, "\n};\nconst size_t runtime_unit_count = %d;\n", count);
  return ok && ferror(out) == 0;
}

int main(int argc, char **argv) {
  if (argc >= 4 && strcmp(argv[1], "-r") == 0) {
    FILE *out = fopen(argv[2], "wb");
    int ok = out != NULL && embed_units(argc - 3, argv + 3, out);
    if (out != NULL) ok = fclose(out) == 0 && ok;
    if (!ok) fprintf(stderr, "embed: cannot write %s\n", argv[2]);
    return ok ? 0 : 2;
  }
  if (argc != 3) {
    fputs("usage: embed IN OUT\n       embed -r OUT IN...\n", stderr);
    return 2;
  }
  FILE *in = fopen(argv[1], "rb");
  FILE *out = in == NULL ? NULL : fopen(argv[2], "wb");
  int ok = out != NULL && embed(argv[1], in, out);
  if (in != NULL) fclose(in);
  if (out != NULL) ok = fclose(out) == 0 && ok;
  if (!ok) fprintf(stderr, "embed: cannot copy %s to %s\n", argv[1], argv[2]);
  return ok ? 0 : 2;
}
